//【问题描述】输入华氏温度，用下列公式将其转换为摄氏温度并输出。

//C=5/9*(F-32)

//【输入形式】

//一个实数。

//【输出形式】

//转换后的摄氏温度，实数。

//【样例输入】

//请输入一个华氏温度：80

//【样例输出】

//转换得到摄氏温度：26.6667。

#include <iostream>
using namespace std;
int main()
{
    double F, C;
	cout << "请输入一个华氏温度：";
    cin >> F;
    C = 5.0/ 9 * (F - 32);
    cout << "转换得到摄氏温度：" << C << "。"<<endl;
    return 0;
}


